public class UpdateArray {
    public static void main(String[] args) {
        int marks[] = new int[50];
        marks[0] = 10;
        marks[1] = 20;
        marks[2] = 30;

        System.out.println(marks[0]);
        System.out.println(marks[1]);
        System.out.println(marks[2]);

        marks[0] = 100;
        marks[1] = 200;
        marks[2] = 300;

        System.out.println(marks[0]);
        System.out.println(marks[1]);
        System.out.println(marks[2]);
    }
}
